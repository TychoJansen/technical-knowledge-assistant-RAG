"""Download the FreshStack LangChain data once, store it locally and create a fixed dev/test split (`rag prepare`).

The queries, nuggets and reference answers are for evaluation.
Only data/corpus.parquet is used as the assistant's knowledge source.
"""

import json
import random
from typing import Any

import pandas as pd
from datasets import load_dataset

from rag_assistant.config import CORPUS_PATH, DATA_DIR, PROJECT_ROOT, QUERIES_PATH, SPLITS_PATH, STATS_PATH
from rag_assistant.data import language, load_corpus, load_queries, load_split
from rag_assistant.logger import get_logger

logger = get_logger(__name__)

# Relevant datasets on Hugging Face Hub (see https://huggingface.co/freshstack)
CORPUS_DATASET = "freshstack/corpus-oct-2024"
QUERIES_DATASET = "freshstack/queries-oct-2024"
SUBSET = "langchain"

# Random seed for reproducibility of the dev/test split. The dev set is exactly N_DEV queries.
SEED = 42
N_DEV = 60


def prepare_corpus(force: bool) -> None:
    """Download the corpus and store it as a flat parquet file.

    The output data structure is a table with the following columns:
        doc_id: str, unique document ID
        text: str, the document text
        url: str, the URL of the source document
        start_byte: int, the byte offset of the chunk in the source document
        end_byte: int, the byte offset of the end of the chunk in the source document
        repo: str, the source repository (the part of doc_id before the first "/")

    Args:
        force: Re-download the corpus even if it already exists.
    """
    # If the corpus already exists and force is not set, skip downloading.
    if CORPUS_PATH.exists() and not force:
        logger.info(f"[skip] {CORPUS_PATH.relative_to(PROJECT_ROOT)} already exists")
        return

    logger.info(f"[download] {CORPUS_DATASET} ({SUBSET})")
    data = load_dataset(CORPUS_DATASET, SUBSET, split="train")
    metadata = data["metadata"]  # Each column access materialises the full column, so read it once.
    df = pd.DataFrame(
        {
            "doc_id": data["_id"],
            "text": data["text"],
            "url": [m["url"] for m in metadata],
            "start_byte": [m["start_byte"] for m in metadata],
            "end_byte": [m["end_byte"] for m in metadata],
        }
    )
    df["repo"] = df["doc_id"].str.split("/", n=1).str[0]
    df.to_parquet(CORPUS_PATH, index=False)
    logger.info(f"[write] {CORPUS_PATH.relative_to(PROJECT_ROOT)} ({len(df)} chunks)")


def _normalize_tags(tags: list[str] | str | None) -> list[str]:
    """Return tags as a list of strings, whether they come as a list or a delimited string.

    Args:
        tags: The tags as a list, a string delimited by "|", ";" or ",", or None.

    Returns:
        The tags as a list of strings (empty if there are none).
    """
    if tags is None:
        return []
    if isinstance(tags, str):
        return [t for t in tags.replace("|", ",").replace(";", ",").split(",") if t.strip()]
    return [str(t) for t in tags]


def prepare_queries(force: bool) -> None:
    """Download the queries and store them as JSON Lines, one evaluation record per question.

    Writes data/queries.json (JSON Lines despite the extension) with one JSON object per question, with these keys:
        qid: str, unique query ID (the Stack Overflow question ID)
        question: str, the full question text: title and body separated by a blank line.
            This is the only field a retriever may see.
        title: str, the question title
        body: str, the question body
        answer_id: str, ID of the accepted Stack Overflow answer
        reference_answer: str, the text of the accepted answer
        date: str, when the question was asked
        tags: list[str], the Stack Overflow tags of the question
        nuggets: list[dict], the key facts of the answer (generated by GPT-4o), each with:
            id: str, unique nugget ID ("<qid>_<n>")
            text: str, the nugget text
            relevant_corpus_ids: list[str], doc_ids of corpus chunks that support the nugget
            non_relevant_corpus_ids: list[str], doc_ids of judged chunks that do not support the nugget
        relevant_doc_ids: list[str], sorted union of relevant_corpus_ids over all nuggets

    Args:
        force: Re-download the queries even if they already exist.
    """
    # If the queries already exist and force is not set, skip downloading.
    if QUERIES_PATH.exists() and not force:
        logger.info(f"[skip] {QUERIES_PATH.relative_to(PROJECT_ROOT)} already exists")
        return

    logger.info(f"[download] {QUERIES_DATASET} ({SUBSET})")
    data = load_dataset(QUERIES_DATASET, SUBSET, split="test")
    with QUERIES_PATH.open("w", encoding="utf-8") as f:
        for row in data:
            nuggets = [
                {
                    "id": n["_id"],
                    "text": n["text"],
                    "relevant_corpus_ids": list(n["relevant_corpus_ids"] or []),
                    "non_relevant_corpus_ids": list(n["non_relevant_corpus_ids"] or []),
                }
                for n in row["nuggets"]
            ]
            relevant = sorted({doc_id for n in nuggets for doc_id in n["relevant_corpus_ids"]})
            record = {
                "qid": row["query_id"],
                "question": f"{row['query_title']}\n\n{row['query_text']}",
                "title": row["query_title"],
                "body": row["query_text"],
                "answer_id": row["answer_id"],
                "reference_answer": row["answer_text"],
                "date": str(row["metadata"]["date"]),
                "tags": _normalize_tags(row["metadata"]["tags"]),
                "nuggets": nuggets,
                "relevant_doc_ids": relevant,
            }
            f.write(json.dumps(record, ensure_ascii=False) + "\n")
    logger.info(f"[write] {QUERIES_PATH.relative_to(PROJECT_ROOT)} ({len(data)} queries)")


def make_split(queries: list[dict[str, Any]]) -> dict[str, Any]:
    """Create a dev/test split of N_DEV dev queries, stratified by language.

    Args:
        queries: Query records, as returned by load_queries.

    Returns:
        Dict with keys "seed" (int), "dev" and "test" (sorted lists of query IDs).
    """
    # Group queries by language, then shuffle and split each group into dev/test.
    by_lang: dict[str, list[str]] = {}
    for q in queries:
        by_lang.setdefault(language(q), []).append(q["qid"])

    rng = random.Random(SEED)
    total = len(queries)
    dev: list[str] = []
    test: list[str] = []
    langs = sorted(by_lang)
    remaining_dev = N_DEV
    for i, lang in enumerate(langs):
        qids = sorted(by_lang[lang])
        rng.shuffle(qids)
        # The last group takes the remainder so the dev set is exactly N_DEV. With only two groups (js, python)
        # this remainder cannot go negative from rounding.
        n_dev = remaining_dev if i == len(langs) - 1 else round(N_DEV * len(qids) / total)
        remaining_dev -= n_dev
        dev.extend(qids[:n_dev])
        test.extend(qids[n_dev:])
    return {"seed": SEED, "dev": sorted(dev), "test": sorted(test)}


def prepare_split(resplit: bool) -> dict[str, Any]:
    """Create splits.json if missing (or if resplit is set) and return the split.

    Args:
        resplit: Recreate splits.json even if it already exists.

    Returns:
        Dict with keys "seed" (int), "dev" and "test" (lists of query IDs).
    """
    if SPLITS_PATH.exists() and not resplit:
        logger.info(f"[skip] {SPLITS_PATH.relative_to(PROJECT_ROOT)} already exists")
        return load_split()

    split = make_split(load_queries())
    SPLITS_PATH.write_text(json.dumps(split, indent=2) + "\n", encoding="utf-8")
    logger.info(f"[write] {SPLITS_PATH.relative_to(PROJECT_ROOT)} (dev={len(split['dev'])}, test={len(split['test'])})")
    return split


def compute_stats(split: dict[str, Any]) -> dict[str, Any]:
    """Run sanity checks on the local files and compute summary statistics.

    Args:
        split: Dict with keys "seed", "dev" and "test", as returned by prepare_split.

    Returns:
        Dict of summary statistics (written to data/stats.json).
    """
    corpus = load_corpus(columns=["doc_id", "text", "repo"])
    queries = load_queries()
    corpus_ids = set(corpus["doc_id"])

    all_relevant = {doc_id for q in queries for doc_id in q["relevant_doc_ids"]}
    missing = sorted(all_relevant - corpus_ids)

    lengths = corpus["text"].str.len()
    lang_by_qid = {q["qid"]: language(q) for q in queries}

    def lang_counts(qids: list[str]) -> dict[str, int]:
        counts = {"js": 0, "python": 0}
        for qid in qids:
            counts[lang_by_qid[qid]] += 1
        return counts

    return {
        "n_chunks": len(corpus),
        "n_queries": len(queries),
        "n_unique_relevant_doc_ids": len(all_relevant),
        "n_relevant_doc_ids_missing_from_corpus": len(missing),
        "missing_relevant_doc_ids_sample": missing[:10],
        "chunk_length_chars": {
            "min": int(lengths.min()),
            "median": float(lengths.median()),
            "mean": round(float(lengths.mean()), 1),
            "p95": float(lengths.quantile(0.95)),
            "max": int(lengths.max()),
        },
        "chunks_per_repo": {k: int(v) for k, v in corpus["repo"].value_counts().items()},
        "avg_nuggets_per_query": round(sum(len(q["nuggets"]) for q in queries) / len(queries), 2),
        "avg_relevant_docs_per_query": round(sum(len(q["relevant_doc_ids"]) for q in queries) / len(queries), 2),
        "split": {
            "seed": split["seed"],
            "dev": {"n": len(split["dev"]), **lang_counts(split["dev"])},
            "test": {"n": len(split["test"]), **lang_counts(split["test"])},
        },
    }


def log_stats(stats: dict[str, Any]) -> None:
    """Log the summary statistics of the corpus and queries.

    Args:
        stats: Summary statistics, as returned by compute_stats.
    """
    logger.info("=== Statistics ===")
    logger.info(f"Chunks:  {stats['n_chunks']}")
    logger.info(f"Queries: {stats['n_queries']}")
    logger.info(f"Unique relevant doc_ids: {stats['n_unique_relevant_doc_ids']}")
    n_missing = stats["n_relevant_doc_ids_missing_from_corpus"]
    if n_missing:
        logger.warning(
            f"{n_missing} relevant doc_ids not found in corpus, e.g. {stats['missing_relevant_doc_ids_sample']}"
        )
    else:
        logger.info("Relevant doc_ids missing from corpus: 0 (OK)")
    cl = stats["chunk_length_chars"]
    logger.info(
        f"Chunk length (chars): min={cl['min']} median={cl['median']:.0f} mean={cl['mean']:.0f} "
        f"p95={cl['p95']:.0f} max={cl['max']}"
    )
    logger.info("Chunks per repo:")
    for repo, n in stats["chunks_per_repo"].items():
        logger.info(f"  {repo:<40} {n}")
    logger.info(f"Avg nuggets per query:       {stats['avg_nuggets_per_query']}")
    logger.info(f"Avg relevant docs per query: {stats['avg_relevant_docs_per_query']}")
    for name in ("dev", "test"):
        s = stats["split"][name]
        logger.info(f"Split {name:<4}: n={s['n']} (js={s['js']}, python={s['python']})")


def prepare(force: bool = False, resplit: bool = False) -> None:
    """Prepare all local data files and log their statistics.

    Args:
        force: Re-download corpus and queries (keeps splits.json).
        resplit: Recreate splits.json (does not touch corpus or queries).
    """
    DATA_DIR.mkdir(exist_ok=True)
    prepare_corpus(force)
    prepare_queries(force)
    split = prepare_split(resplit)

    stats = compute_stats(split)
    STATS_PATH.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    log_stats(stats)
    logger.info(f"[write] {STATS_PATH.relative_to(PROJECT_ROOT)}")
